# D03: censored least absolute deviations (CLAD), Powell's estimator of the
# median of U = min(x beta + e, 1) (quantreg::crq, method "Powell", censored
# above at 1, tau = 0.5).
# Variants (parametric_variants): the D01 forms. lasso_dummies selects item
# dummies with a gaussian lasso at lambda.1se over the folds of the data it is
# given, then refits CLAD; if no column is kept the model is intercept-only.
# Point prediction: the censored median min(x beta, 1); it is not E[U | x].
# Draws: CLAD has no predictive distribution, so draws are
# residual_draws(mu, oof_mu, oof_resid, M): out-of-fold residuals sampled
# within the decile of the OOF predictions that matches mu. The full-health
# share of these draws is about half the observed one and about 24% of draws
# fall in the impossible gap (see residual_draws()), a reported limitation;
# the engine rounds the gap (.round_gap).
# Not converged: crq warned "Max iterations reached" or a pivot error, or a
# coefficient is not finite. "Solution may be nonunique" is muffled and noted
# as fit$nonunique. Every other warning is passed on.

.method_D03 <- function() {
  list(
    id = "D03_clad", family = "direct",
    sets = METHOD_INFO$D03_clad$sets,
    variants = function(set) parametric_variants(set),
    aliases = c("D03", "clad"),
    needs = c("quantreg", "glmnet"),
    predict_needs = character(0),
    uses_oof = TRUE,
    fit = function(train, set, variant, oof = NULL) {
      f <- .d03_fit(train, list(set = set, variant = variant), oof)
      f$set <- set
      f$variant <- variant
      f$converged <- isTRUE(f$fit_info$converged)
      f
    },
    point = function(fit, newdata) .d03_predict_mean(fit, newdata),
    draw = function(fit, newdata, M, key, draw_type, lo, pool = NULL) .d03_draw(fit, newdata, M, key, pool)
  )
}

# Forms of the parametric methods: item sets numeric or lasso over item
# dummies; T-score sets linear, quadratic, spline3, and spline3_int in S3
parametric_variants <- function(set) {
  forms <- if (is_item_set(set)) c("numeric", "lasso_dummies") else
    c("linear", "quadratic", "spline3", if (set == "S3") "spline3_int")
  lapply(forms, function(f) list(form = f))
}

# Powell warnings that mean the algorithm did not reach a solution
.d03_converged <- function(warnings) !any(grepl("Max iterations|Error in pivot", warnings))

# Starting basis for Powell's algorithm: p row indices of Xi (the design with
# the intercept column). quantreg's default takes the first p observations
# with zero residual in the uncensored median regression; with many tied
# utilities and integer items those rows are often linearly dependent, and
# crq stops with "Singular basic solution generated by 'start'". Here the
# candidates are the same zero-residual rows in the same (index) order,
# followed by the other rows by increasing |residual|, and a pivoted QR keeps
# the first p that are linearly independent. No nonsingular basis is an error.
.d03_start <- function(Xi, y) {
  p <- ncol(Xi)
  rk <- qr(Xi)$rank
  if (rk < p) stop("D03: no nonsingular starting basis (design rank ", rk, " < ", p, ")")
  r <- quantreg::rq.fit(Xi, y, tau = 0.5, method = "br")$residuals
  zero <- which(abs(r) < .Machine$double.eps^(2/3))
  ord <- c(zero, setdiff(order(abs(r)), zero))
  q <- qr(t(Xi[ord, , drop = FALSE]))
  if (q$rank < p) stop("D03: no nonsingular starting basis (design rank ", q$rank, " < ", p, ")")
  ord[sort(q$pivot[seq_len(p)])]
}

# One CLAD fit, without the out-of-fold step. Only the coefficients and the
# design spec are kept (the crq object carries formula environments).
.d03_core_fit <- function(train, spec) {
  d <- .direct_design(train, spec)
  X <- d$X
  y <- train$y
  yc <- rep(1, length(y))
  w <- character(0)
  fit <- withCallingHandlers({                         # the start's rq.fit() can warn too
    h <- .d03_start(cbind(1, X), y)
    if (ncol(X)) quantreg::crq(quantreg::Curv(y, yc, ctype = "right") ~ X, taus = 0.5, method = "Powell", start = h)
    else quantreg::crq(quantreg::Curv(y, yc, ctype = "right") ~ 1, taus = 0.5, method = "Powell", start = h)
  },
    warning = function(cnd) {
      w <<- c(w, conditionMessage(cnd))
      if (grepl("Solution may be nonunique", conditionMessage(cnd))) invokeRestart("muffleWarning")
    })
  beta <- unname(stats::coef(fit))
  list(ref = d$ref, design_form = d$design_form, cols = d$cols, beta = beta,
       nonunique = any(grepl("Solution may be nonunique", w)),
       fit_info = list(converged = .d03_converged(w) && all(is.finite(beta)),
                       aic = NA_real_, bic = NA_real_, n_par = length(beta)))
}

.d03_predict_mean <- function(fit, newdata) {
  X <- build_design(newdata, fit$ref$set, fit$design_form, fit$ref)$X[, fit$cols, drop = FALSE]
  pmin(drop(cbind(1, X) %*% fit$beta), 1)
}

# oof: list or data.frame(oof_mu, oof_resid) = core fit with that pool stored;
# FALSE = core fit only, no pool (point predictions only); NULL = the pipeline
# route: the pool from out-of-fold fits over train$fold, with foldid stored
.d03_fit <- function(train, spec, oof = NULL) {
  if (isFALSE(oof)) return(.d03_core_fit(train, spec))
  if (!is.null(oof)) {
    f <- .d03_core_fit(train, spec)
    f$oof_mu <- oof$oof_mu
    f$oof_resid <- oof$oof_resid
    return(f)
  }
  if (is.null(train$fold)) stop("D03 needs train$fold for its out-of-fold residuals")
  f <- .d03_core_fit(train, spec)
  f$oof_mu <- oof_predictions(.d03_core_fit, train, spec, predict_fun = .d03_predict_mean)
  f$oof_resid <- train$y - f$oof_mu
  f$foldid <- train$fold
  f
}

# pool: data.frame(oof_mu, oof_resid) from the bundle (.boot_pool()); NULL = the fit's own pairs
.d03_draw <- function(fit, newdata, M, key, pool = NULL) {
  oof_mu <- if (is.null(pool)) fit$oof_mu else pool$oof_mu
  oof_resid <- if (is.null(pool)) fit$oof_resid else pool$oof_resid
  if (is.null(oof_mu)) {
    stop("this D03 fit has no residual pairs (it was fitted with oof = FALSE) and cannot draw",
         call. = FALSE)
  }
  mu <- .d03_predict_mean(fit, newdata)
  n <- length(mu)
  if (identical(as.integer(key), seq_len(n))) {
    return(residual_draws(mu, oof_mu, oof_resid, M))
  }
  K <- max(key)
  U <- matrix(stats::runif(K * M), K, M)
  g <- .rd_groups(mu, oof_mu)
  out <- matrix(NA_real_, n, M)
  for (k in unique(g$key)) {
    rows <- which(g$key == k)
    # sorted, so a shared U selects the same quantile in every pool (within_id = "common")
    r <- sort(oof_resid[g$bin %in% as.integer(strsplit(k, ",")[[1]])])
    idx <- pmax(1L, ceiling(U[key[rows], , drop = FALSE] * length(r)))
    out[rows, ] <- mu[rows] + matrix(r[idx], length(rows), M)
  }
  out
}

# The decile of each oof_mu (bin) and, for each mu, the pool of deciles it
# draws from (key, "1,2" for pooled deciles); see residual_draws()
.rd_groups <- function(mu, oof_mu) {
  nb  <- min(10L, length(oof_mu))
  bin <- ceiling(nb * rank(oof_mu, ties.method = "first") / length(oof_mu))
  lower <- vapply(seq_len(nb), function(b) min(oof_mu[bin == b]), numeric(1))
  upper <- vapply(seq_len(nb), function(b) max(oof_mu[bin == b]), numeric(1))
  key <- vapply(mu, function(x) {
    hit <- which(lower <= x & x <= upper)
    if (!length(hit)) hit <- findInterval(x, upper[-nb], left.open = TRUE) + 1L
    paste(hit, collapse = ",")
  }, "")
  list(bin = bin, key = key)
}

# Draws mu + residual for methods without a native predictive distribution.
# The out-of-fold predictions oof_mu are split into deciles by rank. A new
# prediction mu draws from the decile whose range [min, max] of oof_mu
# contains it. Edge rule: on a value shared by several deciles (tied oof_mu
# spanning deciles), all of those deciles are pooled, so no tied residual is
# unreachable; in a gap between two deciles' ranges, the upper decile; below
# all oof_mu, the lowest decile; above, the highest. Residuals are sampled
# with replacement. mu, oof_mu and oof_resid must have no missing values.
# Returns n x M.
residual_draws <- function(mu, oof_mu, oof_resid, M) {
  if (!length(oof_mu)) stop("oof_mu is empty")
  if (length(oof_mu) != length(oof_resid)) stop("oof_mu and oof_resid must have the same length")
  if (anyNA(mu) || anyNA(oof_mu) || anyNA(oof_resid)) {
    stop("residual_draws: missing values in mu, oof_mu or oof_resid")
  }
  g <- .rd_groups(mu, oof_mu)
  bin <- g$bin
  key <- g$key
  out <- matrix(NA_real_, length(mu), M)
  for (k in unique(key)) {
    rows <- which(key == k)
    r <- oof_resid[bin %in% as.integer(strsplit(k, ",")[[1]])]
    out[rows, ] <- mu[rows] + matrix(r[sample.int(length(r), length(rows) * M, replace = TRUE)],
                                     length(rows), M)
  }
  out
}

# Out-of-fold mean predictions over train$fold: each fold is predicted by
# fit_fun(train without that fold, spec), whose fit_info must report
# convergence (non-convergence is an error, as in the pipeline's
# .checked_fit). predict_fun must return one non-missing number per held-out
# row, else the fold is named in the error. fit_fun must not itself call
# oof_predictions().
oof_predictions <- function(fit_fun, train, spec, predict_fun) {
  if (is.null(train$fold) || anyNA(train$fold)) stop("train$fold is required, without missing values")
  out <- rep(NA_real_, nrow(train))
  for (k in sort(unique(train$fold))) {
    te <- train$fold == k
    f <- fit_fun(train[!te, , drop = FALSE], spec)
    if (!isTRUE(f$fit_info$converged)) stop("D03 did not converge")
    p <- predict_fun(f, train[te, , drop = FALSE])
    if (!is.numeric(p) || length(p) != sum(te) || anyNA(p)) {
      stop("oof_predictions: predict_fun must return ", sum(te), " numeric values without NA for fold ", k)
    }
    out[te] <- p
  }
  out
}
