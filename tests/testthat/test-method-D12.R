test_that("D12 corrected draws at the bounds are point masses with no NaN", {
  b <- stand_in_bundle("D12_klapproth", "S3K", "UK"); m <- .p2e_method("D12")
  nd <- make_synthetic_data(4, 2); lo <- -0.5
  hi_fit <- b$point; hi_fit$beta[1] <- hi_fit$beta[1] + 5   # mean above 1
  lo_fit <- b$point; lo_fit$beta[1] <- lo_fit$beta[1] - 5   # mean below the minimum
  expect_true(all(m$point(hi_fit, nd) > 1))
  expect_true(all(m$point(lo_fit, nd) < lo))
  d_hi <- withr::with_seed(7, m$draw(hi_fit, nd, 50, 1:4, "corrected", lo))
  d_lo <- withr::with_seed(7, m$draw(lo_fit, nd, 50, 1:4, "corrected", lo))
  expect_false(anyNA(d_hi)); expect_false(anyNA(d_lo))
  expect_true(all(d_hi == 1)); expect_true(all(d_lo == lo))
})
test_that("D12 stored fit is small and holds no model frame or environment", {
  b <- stand_in_bundle("D12_klapproth", "S3K", "UK")
