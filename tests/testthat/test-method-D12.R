test_that("D12 point is the unclamped Klapproth mean and draws centre on the clamped point", {
  b <- stand_in_bundle("D12_klapproth", "S3K", "UK"); nd <- make_synthetic_data(30, 2); m <- .p2e_method("D12")
  lo <- .vs_min(p2e_value_set("UK")); mu <- pmin(pmax(m$point(b$point, nd), lo), 1)
  dc <- withr::with_seed(5, m$draw(b$point, nd, 4000, 1:30, "corrected", lo))
  expect_equal(rowMeans(dc), mu, tolerance = 0.01)
  dp <- withr::with_seed(5, m$draw(b$point, nd, 10, 1:30, "as_published", lo))
  expect_equal(dp, withr::with_seed(5, m$point(b$point, nd) + matrix(rnorm(300, 0, b$point$sigma), 30, 10)))
})
