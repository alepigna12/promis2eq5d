test_that("D12 keyed draws: rows sharing a key get identical draws", {
  b <- stand_in_bundle("D12_klapproth", "S3K", "UK"); m <- .p2e_method("D12")
  nd <- make_synthetic_data(4, 2)[c(1, 1, 2, 3), ]; key <- c(1L, 1L, 2L, 3L)
  lo <- .vs_min(p2e_value_set("UK"))
  d <- withr::with_seed(6, m$draw(b$point, nd, 8, key, "corrected", lo))
  expect_equal(dim(d), c(4L, 8L))
  expect_identical(d[1, ], d[2, ])
  expect_false(isTRUE(all.equal(d[1, ], d[3, ])))
  expect_true(all(is.finite(d)))
})
